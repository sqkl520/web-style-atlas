const pad = (s, n) => {
  // 中文按 2 宽度近似对齐
  let w = 0;
  for (const ch of s) w += /[\u4e00-\u9fa5]/.test(ch) ? 2 : 1;
  return s + ' '.repeat(Math.max(0, n - w));
};

const L = [];
L.push('| # | 行业词 | 30 案层 | 3 模板层 | 界面实际怎么说 | 判定 |');
L.push('| --- | --- | --- | --- | --- | --- |');

let i = 0;
for (const r of rows) {
  i++;
  const s = live.searched[r.term] || {};
  const c = live.chipped[r.term];

  // 30 案层
  const A = r.inIndex
    ? (r.direct || []).length ? '直连 ' + r.direct.join(' ') : '近似 ' + (r.near || []).join(' ')
    : '— 未收录';

  // 模板层
  let B;
  if (r.tplExact.length) B = '直连 ' + r.tplExact.join(' ');
  else if (r.tplAdj.length) B = '可套用 ' + r.tplAdj.join(' ') + '（相邻候选）';
  else if (TPL_FIT[r.term]) B = '可套用 ' + TPL_FIT[r.term][1] + '（' + TPL_FIT[r.term][0] + '）';
  else B = '不适用';

  // 界面实际
  let UI, V;
  if (s.rows > 0 && s.stripVisible) {
    UI = '方案 ' + s.rows + ' 行 + 模板带';
    V = '✓';
  } else if (s.rows > 0) {
    UI = '方案 ' + s.rows + ' 行，不提模板';
    V = (TPL_FIT[r.term] || r.tplAdj.length) ? '~' : '✓';
  } else if (/都给不了你/.test(s.emptyTpl || '')) {
    UI = '0 行 +「图集和模板层都给不了你」';
    V = (TPL_FIT[r.term] || r.tplExact.length) ? '✗' : '✓';
  } else if (/下面只是相邻候选/.test(s.emptyTpl || '')) {
    UI = '0 行 + 相邻候选 + 免责句';
    V = '✓';
  } else if (/但模板层有|另外模板层有/.test(s.emptyTpl || '')) {
    UI = '0 行 + 点名模板 ' + (r.tplExact[0] || '');
    V = '✓';
  } else {
    UI = '0 行 + 芯片能筛 ' + (c ? c.rows : '?') + ' 行';
    V = '~';
  }

  L.push(`| ${i} | ${r.term} | ${A} | ${B} | ${UI} | ${V} |`);
}

writeFileSync(`${ROOT}/matrix.md`, L.join('\n'), 'utf8');

