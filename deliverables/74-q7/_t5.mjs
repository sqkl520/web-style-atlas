import http from 'node:http';
import { writeFileSync } from 'node:fs';
import { Browser } from '../../tools/taste-skill/skills/taste-skill/scripts/lib/cdp.mjs';
import { decodePNG } from './_png.mjs';
const html='<body style="margin:0;background:#E7E7E0"><div style="height:30px"></div><div id="h1" style="border-top:0.5px solid #1C1A16;height:30px"></div><div style="height:30px"></div><div id="h2" style="border-top:1px solid #1C1A16;height:30px"></div><div style="height:30px"></div><div id="h3" style="border-top:2px solid #1C1A16;height:30px"></div></body>';
const srv=http.createServer((q,s)=>{s.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});s.end(html);});
await new Promise(r=>srv.listen(9612,r));
const b=await Browser.launch({width:400,height:200});
const p=await b.newPage({width:400,height:200,dsf:4});
await p.goto('http://localhost:9612/',{settleMs:300});
const d=await p.screenshot({format:'png'});
writeFileSync('shots/_hair.png',Buffer.from(d,'base64'));
const {w,h,bpp,px}=decodePNG(Buffer.from(d,'base64'));
const x=Math.round(w/2);
const rows=[];
for(let y=0;y<h;y++){const i=(y*w+x)*bpp;rows.push(px[i]);}
let runs=[],prev=null,start=0;
rows.forEach((v,y)=>{const dark=v<200;if(dark!==prev){if(prev!==null)runs.push({y0:start,y1:y-1,n:y-start,min:Math.min(...rows.slice(start,y))});prev=dark;start=y;}});
runs.push({y0:start,y1:h-1,n:h-start,min:Math.min(...rows.slice(start))});
console.log('dsf4 dark runs (device px):',runs.filter(r=>r.min<200));
await b.close();srv.close();
