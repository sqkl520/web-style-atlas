ALIAS = {"-": "dash", ".": "dot", "%": "pct", "\u00b0": "deg", "\u2212": "dash"}
# 单位符号要占两格：℃ = 度号 + C，℉ = 度号 + F（字模里没有现成的合成字形）
EXPAND = {"\u2103": ["deg", "C"], "\u2109": ["deg", "F"]}


def glyph_path(rows):
    seg = []
    for y, row in enumerate(rows):
        x = 0
        while x < 5:
            if row[x] == "1":
                run = 1
                while x + run < 5 and row[x + run] == "1":
                    run += 1
                seg.append(f"M{x} {y}h{run}v1h-{run}z")
                x += run
            else:
                x += 1
    return "".join(seg)


def defs_markup():
    out = []
    for name, rows in G.items():
        out.append(f'<g id="dg-{name}"><path d="{glyph_path(rows)}"/></g>')
    return "\n".join(out)


def readout(text, label, cell="1"):
    """生成一段 5x7 点阵读数：逐字 <use>，字距 1 格，viewBox 按字数算。"""
    keys = []
    for ch in text:
        if ch in EXPAND:
            keys.extend(EXPAND[ch])
            continue
        k = ALIAS.get(ch, ch)
        if k not in G:
            raise KeyError(ch)
        keys.append(k)
    width = len(keys) * 6 - 1
    uses = "".join(f'<use href="#dg-{k}" x="{i * 6}"/>' for i, k in enumerate(keys))
    return (f'<svg class="lattice" viewBox="0 0 {width} 7" role="img" aria-label="{label}">'
            f'<g class="lattice-cells">{uses}</g></svg>')


def inject(page: Path) -> bool:
    """把字模 defs 注进 index.html 的 <!--lattice:defs--> 与 </defs> 之间（幂等）。"""
    import re
    if not page.exists():
        return False
    html = page.read_text(encoding="utf-8")
    new, n = re.subn(r"<!--lattice:defs-->.*?(?=</defs>)",
                     lambda m: "<!--lattice:defs-->\n" + defs_markup() + "\n",
                     html, flags=re.S)
    if not n:
        return False
    if new != html:
        page.write_text(new, encoding="utf-8")
    return True


