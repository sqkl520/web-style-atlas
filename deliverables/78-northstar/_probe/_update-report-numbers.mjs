let applied = 0;
for (const [from, to] of RULES) {
  if (s.includes(from)) { s = s.split(from).join(to); applied++; }
  else console.log('未命中（可能已被改过）:', from.slice(0, 60));
}
writeFileSync(P, s);
console.log(`\n应用 ${applied}/${RULES.length} 条替换，文件已写。`);

/* 剩下来的可疑数字，供人工判断 */
const left = [...s.matchAll(/(?:64|4\.2%|27\/640|57 个)/g)];
if (left.length) {
  const lines = s.split('\n');
  console.log('\n仍含旧数字的行（需人工确认是否需要改）:');
  lines.forEach((l, i) => {
    if (/(?:64 hit|\b64 个|4\.2%|27\/640|57 个)/.test(l)) console.log(`  ${i + 1}: ${l.trim().slice(0, 100)}`);
  });
}
