# Runner template, version 2: records progress so failures are diagnosable.
$runnerLines = @(
    '$ProgressPreference = "SilentlyContinue"'
    '$ErrorActionPreference = "Continue"'
    '$home_ = $args[0]'
    '$work_ = $args[1]'
    '$log = Join-Path $work_ "stream.jsonl"'
    '"START " + (Get-Date -Format o) | Set-Content -Path $log -Encoding utf8'
    'try {'
    '    $env:PATH = "C:\tmp\bb-bin;C:\Windows\System32;C:\Windows"'
    '    $env:HOME = $home_'
    '    $env:USERPROFILE = $home_'
    '    $env:ANTHROPIC_API_KEY = "PROXY_MANAGED"'
    '    $env:ANTHROPIC_BASE_URL = "http://127.0.0.1:15721"'
    '    $env:CLAUDE_CODE_EFFORT_LEVEL = "max"'
    '    Add-Content -Path $log -Value "ENV_OK" -Encoding utf8'
    '    Set-Location $work_'
    '    Add-Content -Path $log -Value ("CWD:" + (Get-Location)) -Encoding utf8'
    '    $msg = "Please read task.txt in the current directory and complete the work described there. Output as few words as possible."'
    '    Add-Content -Path $log -Value "LAUNCHING" -Encoding utf8'
    '    $out = & "C:\tmp\bb-bin\claude.exe" -p $msg --model opus --permission-mode acceptEdits --output-format stream-json --verbose 2>&1'
    '    Add-Content -Path $log -Value ("EXITCODE:" + $LASTEXITCODE) -Encoding utf8'
    '    $out | ForEach-Object { Add-Content -Path $log -Value $_ -Encoding utf8 }'
    '} catch {'
    '    Add-Content -Path $log -Value ("FATAL:" + $_.Exception.Message) -Encoding utf8'
    '}'
    'Add-Content -Path $log -Value ("END " + (Get-Date -Format o)) -Encoding utf8'
)
$runnerLines -join "`r`n" | Set-Content -Path 'C:\tmp\runner-template.ps1' -Encoding ASCII
Write-Host 'runner template v2 written'
